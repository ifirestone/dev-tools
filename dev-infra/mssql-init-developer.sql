-- Variables sqlcmd: $(DEV_USER) y $(DEV_PASSWORD), pasadas por mssql-init-developer.sh
IF NOT EXISTS (SELECT 1 FROM sys.server_principals WHERE name = '$(DEV_USER)')
BEGIN
    CREATE LOGIN [$(DEV_USER)] WITH PASSWORD = '$(DEV_PASSWORD)', CHECK_POLICY = OFF, CHECK_EXPIRATION = OFF;
END
ELSE
BEGIN
    ALTER LOGIN [$(DEV_USER)] WITH PASSWORD = '$(DEV_PASSWORD)', CHECK_POLICY = OFF, CHECK_EXPIRATION = OFF;
END
GO

ALTER SERVER ROLE [sysadmin] ADD MEMBER [$(DEV_USER)];
GO

IF NOT EXISTS (SELECT 1 FROM sys.databases WHERE name = '$(DEV_USER)')
BEGIN
    CREATE DATABASE [$(DEV_USER)];
END
GO

ALTER AUTHORIZATION ON DATABASE::[$(DEV_USER)] TO [$(DEV_USER)];
GO
